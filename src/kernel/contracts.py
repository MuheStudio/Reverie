class V3FrameAdapter:
    """Development-only compatibility boundary; production never downgrades."""

    legacy_protocol_version: ClassVar[int] = 3

    @staticmethod
    def to_v4(frame: dict[str, Any], persona: PersonaScopeV4) -> CommandEnvelopeV4:
        if not isinstance(frame, dict):
            raise TypeError("legacy frame must be an object")
        command = frame.get("type")
        payload = frame.get("payload", {})
        if not isinstance(command, str) or command not in MVP_COMMAND_NAMES:
            raise ValueError("legacy frame has an unknown command")
        if not isinstance(payload, dict):
            raise TypeError("legacy frame payload must be an object")
        request_id = str(frame.get("request_id") or uuid4().hex)
        idempotency_key = str(
            payload.get("idempotency_key")
            or payload.get("client_request_id")
            or request_id
        )
        return CommandEnvelopeV4(
            request_id=request_id,
            idempotency_key=idempotency_key,
            command=command,
            persona=persona,
            payload=payload,
        )

    @staticmethod
    def result_to_v3(
        result: CommandResultV4,
        *,
        response_type: str,
    ) -> dict[str, Any]:
        if result.ok:
            payload = result.data
        else:
            assert result.error is not None
            payload = {
                "ok": False,
                "error": {
                    "code": result.error.code.value,
                    "message": result.error.message,
                    "retryable": result.error.retryable,
                },
            }
        return {
            "type": response_type,
            "request_id": result.request_id,
            "payload": payload,
        }


