class ChatStopPayload(_PayloadModel):
    """Legacy stop alias.

    ``request_id`` is optional because ``handle_chat_stop`` answers with a
    dedicated ERROR frame instead of a generic validation failure when the
    controller does not name a specific request (global cancellation is
    forbidden by design).
    """

    request_id: str | None = Field(default=None, max_length=128)

    @field_validator("request_id")
    @classmethod
    def validate_request_id(cls, value: str | None) -> str | None:
        if value is not None and not _ID_PATTERN.fullmatch(value):
            raise ValueError("request_id contains unsupported characters")
        return value


class AIUsageGrantPayload(_PayloadModel):
    """Per-feature consent grant. Booleans must be exactly ``True`` to mirror
    the bridge handler's ``is not True`` checks (no truthy coercion)."""

    model_config = ConfigDict(strict=True, extra="forbid", frozen=True)

    feature: str = Field(min_length=1, max_length=80)
    consent_digest: str = Field(min_length=1, max_length=128)
    api_cost_acknowledged: StrictBool
    user_confirmed: StrictBool

    @field_validator("api_cost_acknowledged", "user_confirmed")
    @classmethod
    def must_be_true(cls, value: bool) -> bool:
        if value is not True:
            raise ValueError("explicit confirmation must be exactly true")
        return value


