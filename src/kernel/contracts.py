class PersonaImportPayload(_PayloadModel):
    """Untrusted SillyTavern JSON card; the importer re-validates size/depth.

    The wire field is ``json``; the attribute is ``json_text`` (serialized
    back as ``json`` via the alias) to avoid shadowing pydantic's historical
    ``json`` helper attribute.
    """

    model_config = ConfigDict(serialize_by_alias=True, extra="forbid", frozen=True)

    json_text: str = Field(
        alias="json",
        validation_alias="json",
        min_length=1,
        max_length=2_000_000,
    )
    filename: str = Field(default="character.json", min_length=1, max_length=256)


