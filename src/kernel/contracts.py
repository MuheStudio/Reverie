class ImmersionNearbyPayload(_PayloadModel):
    """Request nearby life context from a user-granted coarse location."""

    latitude: float = Field(ge=-90.0, le=90.0)
    longitude: float = Field(ge=-180.0, le=180.0)
    place_types: list[str] = Field(default_factory=list, max_length=6)
    radius_m: int = Field(default=1200, ge=300, le=5000)

    @field_validator("place_types")
    @classmethod
    def validate_place_types(cls, value: list[str]) -> list[str]:
        allowed = {"restaurant", "shop", "cafe", "supermarket", "park", "mall"}
        seen: list[str] = []
        for item in value:
            kind = str(item).strip().lower()
            if kind in allowed and kind not in seen:
                seen.append(kind)
        return seen


