def public_error_message(error: BaseException) -> str:
    """Return a bounded message that cannot impersonate the companion."""

    code = str(getattr(error, "code", "") or "")
    known = {
        "REVERIE_SECURE_STORAGE_UNAVAILABLE": "系统安全凭据存储当前不可用。",
        "REVERIE_VAULT_CORRUPT": "本地凭据保险库无法解密，请先清理或恢复。",
        "REVERIE_VAULT_IO": "本地凭据保险库无法读写。",
    }
    return known.get(code, "请求未完成。技术详情已写入本地日志。")
